import {Core,worlds} from './climb-passage-fixture.mjs';
import {walkPassage} from './climb-passage-route.mjs';
import fs from 'node:fs';
const tapes={};
for(const w of worlds)for(const def of w.rooms.filter(d=>d.atlasTransit)){
 const spawn=def.map.find(row=>row.includes('P')).indexOf('P'),direction=spawn<def.cols/2?1:-1;
 const {complete,g,recorded}=walkPassage(Core,def,direction);
 if(!complete||g.deaths)throw new Error(def.id);
 const tape=[];for(const k of recorded){if(tape.at(-1)?.[1]===k)tape.at(-1)[0]++;else tape.push([1,k]);}tapes[def.id]=tape;
}
fs.writeFileSync(new URL('../public/bladefall-climb-passage-tapes.js',import.meta.url),'/* Generated by scripts/build-climb-passage-tapes.mjs. */\n(function(root){root.BladefallClimbPassageTapes='+JSON.stringify(tapes)+';})(typeof window!==\'undefined\'?window:globalThis);\n');
console.log('Recorded all twelve distinct passage routes.');
