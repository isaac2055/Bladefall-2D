// Shared by the Explore route tools (7.341): serve public/, read and write public/bladefall-explore-routes.js,
// and play a route through the game's real Watch in a normal (non-TAS) page to see where it ends.
import {createServer} from 'node:http';
import {readFile,writeFile} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {resolve,extname} from 'node:path';
import {fileURLToPath} from 'node:url';

export const REPO=fileURLToPath(new URL('../../',import.meta.url));
export const PUBLIC=resolve(REPO,'public');
export const ROUTES=resolve(PUBLIC,'bladefall-explore-routes.js');
export const SEED=0xB07,VIEW={w:1440,h:900};
const TYPES={'.html':'text/html','.js':'application/javascript','.json':'application/json','.css':'text/css','.png':'image/png','.mp3':'audio/mpeg','.ogg':'audio/ogg','.svg':'image/svg+xml','.webmanifest':'application/manifest+json'};

export async function serve(){
 const server=createServer(async(req,res)=>{let body;try{const p=resolve(PUBLIC,'.'+decodeURIComponent(new URL(req.url,'http://x').pathname));if(!p.startsWith(PUBLIC))throw 0;body=await readFile(p);}catch{res.writeHead(404);res.end();return;}
  res.writeHead(200,{'Content-Type':TYPES[extname(req.url.split('?')[0])]||'application/octet-stream'});res.end(body);});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 return {server,url:`http://127.0.0.1:${server.address().port}`};
}
export async function readRoutes(){
 if(!existsSync(ROUTES))return {version:1,view:VIEW,seed:SEED,meta:null,stages:{}};
 const g={};new Function('globalThis',await readFile(ROUTES,'utf8'))(g);return g.BladefallExploreRoutes;
}
export async function writeRoutes(routes){
 const stages=Object.fromEntries(Object.entries(routes.stages).sort((a,b)=>+a[0]-+b[0]));
 await writeFile(ROUTES,'/* Generated by scripts/explore-routes (build.mjs: the traversal bot; add.mjs: your exported recordings). Explore\'s\n   intended routes: each stage\'s button states from the level-select start, replayed by Watch in the level select. */\n'+
  'globalThis.BladefallExploreRoutes='+JSON.stringify({version:1,view:routes.view||VIEW,seed:routes.seed??SEED,meta:routes.meta,stages})+';\n');
}
// Plays `route` for `stage` through exploreWatchStart in a normal game page at 8×; returns the watch's log entry.
export async function watchRoute(browser,url,routes,stage,route,{timeoutMs=20*60*1000}={}){
 const page=await browser.newPage();await page.setViewport({width:1280,height:720,deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.evaluateOnNewDocument(()=>{try{localStorage.setItem('bladefall.explore.watchSpeed','8');}catch(e){}});
  await page.goto(url+'/index.html',{waitUntil:'load'});
  await page.waitForFunction(()=>typeof exploreWatchStart==='function'&&window.__BF,{timeout:60000});
  await new Promise(r=>setTimeout(r,1000));
  const started=await page.evaluate((routes,stage,route)=>{window.BladefallExploreRoutes={...routes,stages:{[stage]:route}};return exploreWatchStart([stage]);},routes,stage,route);
  if(!started)return {ok:false,reason:'watch did not start',errors};
  const t0=Date.now();
  while(await page.evaluate(()=>!!exploreWatch)){if(Date.now()-t0>timeoutMs)return {ok:false,reason:'watch timed out',errors};await new Promise(r=>setTimeout(r,500));}
  const log=await page.evaluate(()=>window.__exploreWatchLog||[]);
  return {...(log[0]||{ok:false,reason:'no watch result'}),errors};
 }finally{await page.close();}
}
