// Room by Room: writes public/bladefall-rbr-NN-<key>.js from scripts/rbr-src/NN-<key>.mjs (the region's rooms)
// and scripts/rbr-src/NN-<key>.tapes.json (its tapes, filled in by scripts/rbr-find.mjs while authoring).
//   node scripts/rbr-src/gen.mjs 01
import {readdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {dirname,resolve} from 'node:path';
const here=dirname(fileURLToPath(import.meta.url));
const nn=process.argv[2];
const src=readdirSync(here).find(f=>f.startsWith(nn+'-')&&f.endsWith('.mjs'));
if(!src){console.error('no source for region',nn);process.exit(1);}
const key=src.slice(3,-4);
const region=(await import(pathToFileURL(resolve(here,src)).href)).default;
const tf=resolve(here,`${nn}-${key}.tapes.json`);
const tapes=existsSync(tf)?JSON.parse(readFileSync(tf,'utf8')):{};
const lit=v=>JSON.stringify(v);
function room(r,ind=' '){
 const {map,...rest}=r;
 return `${ind}{...${lit(rest)},map:[\n${map.map(row=>`${ind}  ${lit(row)}`).join(',\n')}]}`;
}
const out=`/* Room by Room · ${region.n}. ${region.name} (7.259). Generated by scripts/rbr-src/gen.mjs from scripts/rbr-src/${src}
   and its tapes file; edit those, not this. ${region.note||''}
   Registry and conventions: bladefall-rbr.js and docs/plans/room-by-room.md. */
(function(root){
'use strict';
const RBR=root.BladefallRoomByRoom;if(!RBR)return;
const rooms=[
${region.rooms.map(r=>room(r)).join(',\n')}
];
const quests=[
${(region.quests||[]).map(q=>{const {rooms:qr=[],...qrest}=q;return ` {...${lit(qrest)},rooms:[\n${qr.map(r=>room(r,'  ')).join(',\n')}]}`;}).join(',\n')}
];
const tapes=${lit(tapes)};
RBR.addRegion({...${lit({n:region.n,name:region.name,kit:region.kit,blurb:region.blurb,outro:region.outro,folk:region.folk,props:region.props,palettes:region.palettes})},rooms,quests,tapes});
})(typeof window!=='undefined'?window:globalThis);
`;
const dest=resolve(here,'../../public',`bladefall-rbr-${nn}-${key}.js`);
writeFileSync(dest,out);console.log('wrote',dest,region.rooms.length,'rooms,',(region.quests||[]).reduce((n,q)=>n+(q.rooms||[]).length,0),'quest rooms,',Object.keys(tapes).length,'tapes');
