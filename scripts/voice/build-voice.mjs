// node scripts/voice/build-voice.mjs : writes public/bladefall-voice.js from scripts/voice/lines.json and the clips' lengths.
// A line is listed only when its clip exists under public/audio/voice/<id>.mp3.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';import {createHash} from 'node:crypto';import {execFileSync} from 'node:child_process';
const lines=JSON.parse(readFileSync('scripts/voice/lines.json','utf8')),cast=JSON.parse(readFileSync('scripts/voice/cast.json','utf8'));
const L={},D={},H={};const missing=[];
for(const [id,text] of Object.entries(lines)){const f='public/audio/voice/'+id+'.mp3';if(!existsSync(f)){missing.push(id);continue;}
  L[id]=text;H[id]=createHash('sha1').update(readFileSync(f)).digest('hex').slice(0,8);D[id]=+(+execFileSync('ffprobe',['-v','error','-show_entries','format=duration','-of','csv=p=0',f])).toFixed(2);}
const castNote=Object.entries(cast).map(([who,v])=>who+' · '+v.name).join(' | ');
writeFileSync('public/bladefall-voice.js',`/* Bladefall — SPOKEN LINES. GENERATED by scripts/voice/build-voice.mjs from scripts/voice/lines.json; do not edit by hand.
   Voiced with ElevenLabs (eleven_v4), clips under ./audio/voice/. A line is voiced when the text on screen is exactly one of
   these (compared without case, quotes or punctuation), so a line changed in the Dialogue Editor simply goes back to silent.
   BladefallConversation and the cinematics call play(). Cast: ${castNote} */
(function(root){
'use strict';
const BASE='./audio/voice/';
const LINES=${JSON.stringify(L,null,1)};
const SECONDS=${JSON.stringify(D)};
/* A content stamp per clip, so a re-recorded line is fetched fresh instead of from a cache. */
const STAMP=${JSON.stringify(H)};
const norm=t=>String(t==null?'':t).toLowerCase().replace(/[‘’]/g,"'").replace(/<[^>]*>/g,' ').replace(/[^a-z0-9']+/g,' ').trim();
const index=new Map(Object.entries(LINES).map(([id,text])=>[norm(text),id]));
let current=null;
/* Voice lines can be turned off in Explore's Settings or Ascend's Assist & options; both write this one switch. */
const SWITCH='bladefall.voiceLines';
function setting(){try{if(root.localStorage&&root.localStorage.getItem(SWITCH)==='off')return false;}catch(_e){}try{if(typeof meta!=='undefined'&&meta&&(meta.soundOn===false||meta.voices===false))return false;}catch(_e){}return true;}
function enabled(){return setting();}
function setEnabled(on){try{root.localStorage.setItem(SWITCH,on?'on':'off');}catch(_e){}if(!on)stop();}
function volume(){try{if(typeof meta!=='undefined'&&meta&&typeof meta.sfxVolume==='number')return Math.max(0,Math.min(1,meta.sfxVolume*1.1));}catch(_e){}return .85;}
/* Act Two and the gates mix narration with speech ("<b>OREN</b><br>The chain snaps. “He always did…”"): only the quoted words are voiced. */
function quoted(text){const q=String(text==null?'':text).replace(/<[^>]*>/g,' ').match(/“[^”]*”/g);return q?q.map(s=>s.slice(1,-1)).join(' '):'';}
function clipFor(text){return index.get(norm(text))||index.get(norm(quoted(text)))||null;}
function stop(){if(current){try{current.pause();}catch(_e){}current=null;}}
/* Plays the clip for a line of text, if there is one; returns its length in seconds (0 when silent). */
function play(text){
  stop();const id=clipFor(text);if(!id||!setting()||typeof Audio==='undefined')return 0;
  try{const a=new Audio(BASE+id+'.mp3?v='+(STAMP[id]||''));a.volume=volume();current=a;const p=a.play();if(p&&p.catch)p.catch(()=>{});}catch(_e){return 0;}
  return SECONDS[id]||0;
}
function speaking(){return !!current&&!current.paused&&!current.ended;}
const api=Object.freeze({LINES,SECONDS,clipFor,play,stop,speaking,norm,enabled,setEnabled});
if(typeof module==='object'&&module.exports)module.exports=api;
root.BladefallVoice=api;
})(typeof globalThis!=='undefined'?globalThis:window);
`);
console.log('voiced',Object.keys(L).length,'missing',missing.length?missing.join(', '):'none');
