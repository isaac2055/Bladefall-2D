import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const context={BladefallClimb:{worlds:[],addWorld(w){this.worlds.push(w);}}};
vm.createContext(context);
for(const file of ['bladefall-climb-worlds.js','bladefall-climb-atlas.js'])vm.runInContext(fs.readFileSync(new URL('../public/'+file,import.meta.url),'utf8'),context);
const {worlds}=context.BladefallClimb,{create,links}=context.BladefallClimbAtlas;
const atlas=create(worlds);
assert.equal(worlds.length,9);
assert.equal(links.length,12);
assert.equal(atlas.routes(1).length,2);
assert.ok(atlas.routes(1).every(l=>!l.open));
for(const w of worlds){
 for(const route of atlas.routes(w.n))assert.ok(w.rooms.some(r=>r.id===atlas.endpoint(route.id,w.n)));
 assert.ok(w.rooms.every(r=>(r.dashes??1)===1),'One dash throughout');
}
const end=n=>worlds.find(w=>w.n===n).sections.at(-1).room;
atlas.solve(end(1));
assert.ok(atlas.canTravel(1,2)&&atlas.canTravel(1,3));
assert.ok(atlas.canTravel(2,1));
assert.equal(atlas.canTravel(2,4),false);
assert.equal(atlas.canTravel(1,9),false);
const middle=n=>{const s=worlds.find(w=>w.n===n).sections;return s[Math.floor(s.length/2)].room;};
const left=middle(2),right=middle(3);
atlas.solve(left);
assert.equal(atlas.canTravel(2,3),false);
atlas.solve(right);
assert.equal(atlas.canTravel(2,3),false,'midworld progress never unlocks a crossing');
atlas.solve(end(2));
assert.equal(atlas.canTravel(2,3),false);
atlas.solve(end(3));
assert.ok(atlas.canTravel(2,3)&&atlas.canTravel(3,2));
assert.equal(atlas.visit(3,left),false);
assert.equal(atlas.visit(3,right),true);
const restored=create(worlds,JSON.parse(JSON.stringify(atlas.snapshot())));
assert.ok(restored.canTravel(2,3));
assert.equal(restored.state.checkpoint.room,right);
for(const w of worlds)for(const s of w.sections)restored.solve(s.room);
assert.ok(links.every(l=>restored.canTravel(l.a,l.b)&&restored.canTravel(l.b,l.a)));
assert.equal(restored.routes(9).length,2,'Future crown is reserved, not playable');
assert.equal(restored.canTravel(9,10),false);
const invalid=create(worlds,{version:1,checkpoint:{world:20,room:right},visited:{20:true},solved:{bogus:true},open:{bogus:true}});
assert.equal(invalid.state.checkpoint,null);
assert.equal(invalid.state.visited[20],undefined);
assert.equal(invalid.state.solved.bogus,undefined);
console.log('Atlas: all 12 reciprocal links, solve gates, save reload, endpoints, one dash, and future boundaries verified.');
